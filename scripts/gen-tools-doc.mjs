#!/usr/bin/env node
// Writes docs/TOOLS.md from the MCP server's own tool definitions, so the
// reference never drifts from what agents actually see. Run: npm run docs:tools
import fs from 'node:fs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { FireLab, createMcpServer } from '../dist/index.js';

const lab = new FireLab({ autoReconnect: false, adbPath: '/nonexistent/adb' });
const client = new Client({ name: 'docs', version: '1' });
const [a, b] = InMemoryTransport.createLinkedPair();
await Promise.all([createMcpServer(lab).connect(a), client.connect(b)]);
const { tools } = await client.listTools();
const { prompts } = await client.listPrompts();
await client.close();

const groups = [
  ['Devices', ['list_devices', 'scan_network', 'connect_device', 'device_info', 'wake_device']],
  ['Remote and screen', ['press_keys', 'type_text', 'screenshot']],
  ['Apps', ['list_apps', 'install_app', 'launch_app', 'stop_app', 'reset_app']],
  ['WebView (Chrome DevTools)', ['webview_eval', 'webview_console']],
  ['Performance', ['measure_performance', 'performance_sweep']],
  ['Play sessions and logs', ['watch_start', 'watch_stop', 'logcat']],
  ['Game testing engine', ['explore_start', 'explore_status', 'explore_stop', 'explore_findings']],
];

const typeOf = (s) => {
  if (!s) return 'any';
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.enum) return s.enum.map((e) => `\`${e}\``).join(' \\| ');
  if (s.type === 'array') return `${typeOf(s.items)}[]`;
  if (s.anyOf) return s.anyOf.map(typeOf).join(' \\| ');
  return s.type ?? 'any';
};
const esc = (t) => String(t ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

const out = [
  '# FireLab MCP tools',
  '',
  '<!-- Generated by `npm run docs:tools` from src/mcp/server.ts. Edit the tool definitions, not this file. -->',
  '',
  `FireLab's MCP server (\`firelab mcp\`) exposes ${tools.length} tools and ${prompts.length} prompts. Every tool takes an optional \`device\` (adb serial or IP); with exactly one device connected you can leave it out. Results are JSON (as text and as \`structuredContent\`); \`screenshot\` returns an image. Errors come back as tool errors with a hint, e.g. \`Device 192.168.1.50:5555 has not authorized this computer. Look at the TV and accept the "Allow USB debugging?" prompt [unauthorized]\`.`,
  '',
  'Annotations: **read-only** tools never change the device; tools marked **changes the device** say what they change.',
  '',
];
const byName = Object.fromEntries(tools.map((t) => [t.name, t]));
for (const [title, names] of groups) {
  out.push(`## ${title}`, '');
  for (const n of names) {
    const t = byName[n];
    if (!t) continue;
    const ann = t.annotations ?? {};
    const tag = ann.readOnlyHint ? 'read-only' : ann.destructiveHint ? 'changes the device' : 'acts on the device';
    out.push(`### \`${t.name}\` (${tag})`, '', t.description ?? '', '');
    const props = t.inputSchema?.properties ?? {};
    const req = new Set(t.inputSchema?.required ?? []);
    const keys = Object.keys(props);
    if (keys.length) {
      out.push('| Parameter | Type | Required | Description |', '|---|---|---|---|');
      for (const k of keys) out.push(`| \`${k}\` | ${typeOf(props[k])} | ${req.has(k) ? 'yes' : ''} | ${esc(props[k].description)} |`);
      out.push('');
    } else out.push('No parameters.', '');
  }
}
out.push('## Prompts', '');
for (const p of prompts) {
  out.push(`### \`${p.name}\``, '', p.description ?? '', '');
  if (p.arguments?.length) {
    out.push('| Argument | Required | Description |', '|---|---|---|');
    for (const a of p.arguments) out.push(`| \`${a.name}\` | ${a.required ? 'yes' : ''} | ${esc(a.description)} |`);
    out.push('');
  }
}
out.push(
  '## Key names',
  '',
  '`up down left right ok back home menu playpause rewind fastforward volup voldown mute search wake` (`ok` is the center button). Also accepted: `select`, `enter`, `ff`, `rew`, Android key codes (`66`) and names (`KEYCODE_CHANNEL_UP`). Modifiers: `down*3` (three presses), `ok:long` (long press), `right:1500` (hold 1.5 s).',
  '',
  '## Same features over HTTP and the CLI',
  '',
  'The dashboard API (`firelab ui`, http://localhost:7300/api) and the CLI (`firelab help`) expose the same operations; see [CONTRACT.md](CONTRACT.md) for the HTTP routes and payloads.',
  '',
);
fs.writeFileSync(new URL('../docs/TOOLS.md', import.meta.url), out.join('\n'));
console.error(`wrote docs/TOOLS.md (${tools.length} tools, ${prompts.length} prompts)`);
await lab.close();
