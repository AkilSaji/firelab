/**
 * FireLab's WebView wrapper: a full-screen WebView for Fire TV and Android TV
 * that opens one web app, generated by `firelab wrap`.
 *
 * - The remote's buttons reach the page as keyboard events (arrows, Enter,
 *   media keys), with the legacy keyCode set too.
 * - Back sends Escape to the page. If the page calls preventDefault() on that
 *   keydown, it handled Back; otherwise the WebView goes back in its history,
 *   and at the first page the app exits. Holding Back always exits.
 * - Optional LAN scan: if a dev server on a private address stops answering
 *   (DHCP gave the computer a new address), look for it on this subnet.
 * - DevTools: WebView debugging is on in debug builds, so the FireLab tester
 *   can read window.firelab over the Chrome DevTools Protocol.
 * - The page can call window.FireLabTV.exit() and FireLabTV.info().
 *
 * Settings come from assets/firelab.json, written by `firelab wrap`.
 * Open another URL without rebuilding:
 *   adb shell am start -n <package>/dev.firelab.wrap.MainActivity -e url http://192.168.1.20:8080/
 */
public class MainActivity extends Activity {
    private static final String TAG = "FireLab";
    private static final long HOLD_TO_QUIT_MS = 900;

    private FrameLayout root;
    private WebView web;
    private View customView;
    private WebChromeClient chrome;
    private WebChromeClient.CustomViewCallback customViewCallback;

    private String configUrl = "about:blank";
    private String appName = "App";
    private boolean scanEnabled = false;
    private String scanPath = null;
    private int background = Color.BLACK;
    private boolean debug = true;
    private boolean keepScreenOn = true;
    private String uaSuffix = "FireLab";

    private String currentUrl;
    private boolean showingError = false;
    private boolean searching = false;
    private boolean searchedSinceOk = false;
    private long backDownAt = 0;

    @Override
    protected void onCreate(Bundle state) {
        super.onCreate(state);
        readConfig();
        if (keepScreenOn) getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
        getWindow().addFlags(WindowManager.LayoutParams.FLAG_FULLSCREEN);
        boolean debuggable = (getApplicationInfo().flags & ApplicationInfo.FLAG_DEBUGGABLE) != 0;
        WebView.setWebContentsDebuggingEnabled(debug || debuggable);

        root = new FrameLayout(this);
        root.setBackgroundColor(background);
        setContentView(root);
        hideSystemUi();

        currentUrl = resolveUrl(getIntent());
        createWebView();
        load();
    }

    // ---------- configuration ----------

    private void readConfig() {
        try {
            InputStream in = getAssets().open("firelab.json");
            ByteArrayOutputStream buf = new ByteArrayOutputStream();
            byte[] chunk = new byte[4096];
            int n;
            while ((n = in.read(chunk)) > 0) buf.write(chunk, 0, n);
            in.close();
            JSONObject c = new JSONObject(buf.toString("UTF-8"));
            configUrl = c.optString("url", configUrl);
            appName = c.optString("name", appName);
            scanEnabled = c.optBoolean("scan", false);
            scanPath = c.has("scanPath") ? c.optString("scanPath") : null;
            debug = c.optBoolean("debug", true);
            keepScreenOn = c.optBoolean("keepScreenOn", true);
            uaSuffix = c.optString("userAgent", uaSuffix);
            String bg = c.optString("background", "");
            if (!bg.isEmpty()) background = Color.parseColor(bg);
        } catch (Exception e) {
            Log.e(TAG, "assets/firelab.json unreadable: " + e);
        }
    }

    private SharedPreferences prefs() {
        return getSharedPreferences("firelab", MODE_PRIVATE);
    }

    /** Intent extra "url" (or a VIEW intent's data), then an address found by the LAN scan, then the built-in URL. */
    private String resolveUrl(Intent intent) {
        String fromIntent = null;
        if (intent != null) {
            fromIntent = intent.getStringExtra("url");
            Uri data = intent.getData();
            if ((fromIntent == null || fromIntent.isEmpty()) && data != null && ("http".equals(data.getScheme()) || "https".equals(data.getScheme()))) {
                fromIntent = data.toString();
            }
        }
        if (fromIntent != null && !fromIntent.isEmpty()) {
            if (intent.getBooleanExtra("persist", false)) prefs().edit().putString("url", fromIntent).putString("for", configUrl).apply();
            return fromIntent;
        }
        SharedPreferences p = prefs();
        // A remembered address only counts for the URL it replaced (a rebuild with a new URL starts fresh).
        if (configUrl.equals(p.getString("for", null))) {
            String saved = p.getString("url", null);
            if (saved != null && !saved.isEmpty()) return saved;
        }
        return configUrl;
    }

    @Override
    protected void onNewIntent(Intent intent) {
        super.onNewIntent(intent);
        setIntent(intent);
        if (intent.hasExtra("url") || intent.getData() != null) {
            currentUrl = resolveUrl(intent);
            searchedSinceOk = false;
            load();
        }
    }

    // ---------- the WebView ----------

    private void createWebView() {
        web = new WebView(this);
        web.setBackgroundColor(background);
        web.setFocusable(true);
        web.setFocusableInTouchMode(true);
        root.addView(web, new FrameLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT));

        WebSettings s = web.getSettings();
        s.setJavaScriptEnabled(true);
        s.setDomStorageEnabled(true);
        s.setDatabaseEnabled(true);
        s.setMediaPlaybackRequiresUserGesture(false);
        s.setLoadWithOverviewMode(true);
        s.setUseWideViewPort(true);
        s.setSupportZoom(false);
        s.setBuiltInZoomControls(false);
        s.setCacheMode(WebSettings.LOAD_DEFAULT);
        s.setMixedContentMode(WebSettings.MIXED_CONTENT_ALWAYS_ALLOW);
        s.setUserAgentString(s.getUserAgentString() + " " + uaSuffix);
        web.addJavascriptInterface(new Bridge(), "FireLabTV");

        web.setWebViewClient(new WebViewClient() {
            @Override
            public boolean shouldOverrideUrlLoading(WebView view, WebResourceRequest req) {
                String scheme = req.getUrl().getScheme();
                if ("http".equals(scheme) || "https".equals(scheme) || "about".equals(scheme) || "data".equals(scheme)) return false;
                Log.i(TAG, "ignored link: " + req.getUrl());
                return true; // intent:, market:, mailto: ... have nowhere to go on a TV
            }

            @Override
            public void onPageFinished(WebView view, String url) {
                if (!showingError && url != null && url.startsWith("http")) searchedSinceOk = false;
            }

            @Override
            public void onReceivedError(WebView view, WebResourceRequest req, WebResourceError err) {
                if (!req.isForMainFrame()) return;
                Log.w(TAG, "load failed: " + err.getDescription() + " (" + req.getUrl() + ")");
                if (scanEnabled && !searchedSinceOk && isPrivateHost(currentUrl)) findServer();
                else showUnreachable();
            }

            @Override
            public boolean onRenderProcessGone(WebView view, RenderProcessGoneDetail detail) {
                // Usually a 1 GB stick running out of memory. Rebuild the
                // WebView instead of letting the whole app crash.
                Log.e(TAG, "renderer gone, crashed=" + detail.didCrash());
                root.removeView(web);
                web.destroy();
                createWebView();
                showError("The page ran out of memory and stopped.", true);
                return true;
            }
        });

        chrome = new WebChromeClient() {
            @Override
            public boolean onConsoleMessage(ConsoleMessage m) {
                Log.d(TAG, "[js] " + m.message() + " (" + m.sourceId() + ":" + m.lineNumber() + ")");
                return true;
            }

            // <video> full screen.
            @Override
            public void onShowCustomView(View view, CustomViewCallback callback) {
                if (customView != null) {
                    callback.onCustomViewHidden();
                    return;
                }
                customView = view;
                customViewCallback = callback;
                root.addView(view, new FrameLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT));
                web.setVisibility(View.GONE);
            }

            @Override
            public void onHideCustomView() {
                if (customView == null) return;
                root.removeView(customView);
                customView = null;
                web.setVisibility(View.VISIBLE);
                if (customViewCallback != null) customViewCallback.onCustomViewHidden();
                customViewCallback = null;
                web.requestFocus();
            }
        };
        web.setWebChromeClient(chrome);

        web.requestFocus(View.FOCUS_DOWN);
    }

    private void load() {
        showingError = false;
        Log.i(TAG, "loading " + currentUrl);
        web.loadUrl(currentUrl);
        web.requestFocus();
    }

    /** What the page can call: window.FireLabTV.exit(), window.FireLabTV.info(). */
    private class Bridge {
        @JavascriptInterface
        public void exit() {
            runOnUiThread(new Runnable() {
                @Override
                public void run() {
                    finish();
                }
            });
        }

        @JavascriptInterface
        public String info() {
            JSONObject o = new JSONObject();
            try {
                o.put("model", Build.MODEL);
                o.put("manufacturer", Build.MANUFACTURER);
                o.put("device", Build.DEVICE);
                o.put("sdk", Build.VERSION.SDK_INT);
                o.put("release", Build.VERSION.RELEASE);
                o.put("package", getPackageName());
                PackageInfo pi = getPackageManager().getPackageInfo(getPackageName(), 0);
                o.put("versionName", pi.versionName);
                o.put("wrapper", "firelab");
            } catch (Exception ignored) {
            }
            return o.toString();
        }
    }

    // ---------- errors and the LAN scan ----------

    private void showUnreachable() {
        showError("Can't reach<br><code>" + escapeHtml(currentUrl) + "</code><br><br>"
                + "Check that the server is running and that this TV is on the same network.", true);
    }

    private void showError(String message, boolean canRetry) {
        showingError = true;
        String html = "<html><head><meta name=viewport content='width=device-width'></head>"
                + "<body style=\"margin:0;height:100vh;display:flex;align-items:center;justify-content:center;"
                + "background:#14141c;color:#f2f2f5;font:22px sans-serif;text-align:center\"><div style=\"max-width:80%\">"
                + "<div style=\"font-size:48px;font-weight:700;margin-bottom:24px\">" + escapeHtml(appName) + "</div>"
                + message
                + (canRetry ? "<br><br><span style=\"display:inline-block;background:#ff7a45;color:#14141c;padding:10px 26px;border-radius:30px;font-weight:700\">Press OK to try again</span>" : "")
                + "<div style=\"margin-top:22px;opacity:.6;font-size:18px\">Hold Back to quit</div>"
                + "</div></body></html>";
        web.loadDataWithBaseURL(null, html, "text/html", "utf-8", null);
    }

    private static String escapeHtml(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }

    private static boolean isPrivateHost(String url) {
        try {
            String h = new URL(url).getHost();
            return h.startsWith("10.") || h.startsWith("192.168.") || h.matches("^172\\.(1[6-9]|2\\d|3[01])\\..*");
        } catch (Exception e) {
            return false;
        }
    }

    /** Ask every address on this /24 for the same port and path; use the first that answers. */
    private void findServer() {
        searchedSinceOk = true;
        searching = true;
        showError("Looking for the server on your network…", false);
        final URL saved;
        try {
            saved = new URL(currentUrl);
        } catch (Exception e) {
            searching = false;
            showUnreachable();
            return;
        }
        final int port = saved.getPort() > 0 ? saved.getPort() : saved.getDefaultPort();
        final String probe = scanPath != null && !scanPath.isEmpty() ? scanPath : (saved.getPath().isEmpty() ? "/" : saved.getPath());
        new Thread(new Runnable() {
            @Override
            public void run() {
                final String found = scan(saved.getProtocol(), port, probe);
                runOnUiThread(new Runnable() {
                    @Override
                    public void run() {
                        searching = false;
                        if (found == null) {
                            showUnreachable();
                            return;
                        }
                        String file = saved.getFile().isEmpty() ? "/" : saved.getFile();
                        currentUrl = saved.getProtocol() + "://" + found + file;
                        Log.i(TAG, "found the server at " + currentUrl);
                        prefs().edit().putString("url", currentUrl).putString("for", configUrl).apply();
                        load();
                    }
                });
            }
        }).start();
    }

    private static String scan(final String protocol, int port, final String probe) {
        String subnet = null;
        try {
            for (NetworkInterface ni : Collections.list(NetworkInterface.getNetworkInterfaces())) {
                if (!ni.isUp() || ni.isLoopback()) continue;
                for (InetAddress a : Collections.list(ni.getInetAddresses())) {
                    if (a instanceof Inet4Address && a.isSiteLocalAddress()) {
                        String ip = a.getHostAddress();
                        subnet = ip.substring(0, ip.lastIndexOf('.') + 1);
                    }
                }
            }
        } catch (Exception e) {
            Log.w(TAG, "no network: " + e);
        }
        if (subnet == null) return null;
        final AtomicReference<String> hit = new AtomicReference<>();
        ExecutorService pool = Executors.newFixedThreadPool(48);
        for (int i = 1; i < 255; i++) {
            final String host = subnet + i + ":" + port;
            pool.execute(new Runnable() {
                @Override
                public void run() {
                    if (hit.get() == null && answers(protocol + "://" + host + probe)) hit.compareAndSet(null, host);
                }
            });
        }
        pool.shutdown();
        try {
            pool.awaitTermination(15, TimeUnit.SECONDS);
        } catch (InterruptedException ignored) {
        }
        pool.shutdownNow();
        return hit.get();
    }

    private static boolean answers(String url) {
        HttpURLConnection c = null;
        try {
            c = (HttpURLConnection) new URL(url).openConnection();
            c.setConnectTimeout(700);
            c.setReadTimeout(1500);
            c.setInstanceFollowRedirects(false);
            int code = c.getResponseCode();
            return code >= 200 && code < 400;
        } catch (Exception e) {
            return false;
        } finally {
            if (c != null) c.disconnect();
        }
    }

    // ---------- the remote ----------

    /** Remote button -> { key, code, keyCode } as a browser would send it. */
    private static Object[] keyFor(int code) {
        switch (code) {
            case KeyEvent.KEYCODE_DPAD_UP: return new Object[] {"ArrowUp", "ArrowUp", 38};
            case KeyEvent.KEYCODE_DPAD_DOWN: return new Object[] {"ArrowDown", "ArrowDown", 40};
            case KeyEvent.KEYCODE_DPAD_LEFT: return new Object[] {"ArrowLeft", "ArrowLeft", 37};
            case KeyEvent.KEYCODE_DPAD_RIGHT: return new Object[] {"ArrowRight", "ArrowRight", 39};
            case KeyEvent.KEYCODE_DPAD_CENTER:
            case KeyEvent.KEYCODE_ENTER:
            case KeyEvent.KEYCODE_NUMPAD_ENTER: return new Object[] {"Enter", "Enter", 13};
            case KeyEvent.KEYCODE_MENU: return new Object[] {"ContextMenu", "ContextMenu", 93};
            case KeyEvent.KEYCODE_MEDIA_PLAY_PAUSE: return new Object[] {"MediaPlayPause", "MediaPlayPause", 179};
            case KeyEvent.KEYCODE_MEDIA_PLAY: return new Object[] {"MediaPlay", "MediaPlay", 250};
            case KeyEvent.KEYCODE_MEDIA_PAUSE: return new Object[] {"MediaPause", "MediaPause", 19};
            case KeyEvent.KEYCODE_MEDIA_REWIND: return new Object[] {"MediaRewind", "MediaRewind", 227};
            case KeyEvent.KEYCODE_MEDIA_FAST_FORWARD: return new Object[] {"MediaFastForward", "MediaFastForward", 228};
            case KeyEvent.KEYCODE_MEDIA_NEXT: return new Object[] {"MediaTrackNext", "MediaTrackNext", 176};
            case KeyEvent.KEYCODE_MEDIA_PREVIOUS: return new Object[] {"MediaTrackPrevious", "MediaTrackPrevious", 177};
            default: return null;
        }
    }

    /** Dispatches a KeyboardEvent (with keyCode/which for older code); the callback gets "true" if the page called preventDefault(). */
    private void sendKey(String type, String key, String code, int keyCode, boolean repeat, ValueCallback<String> done) {
        sendKey(type, key, code, keyCode, repeat, null, done);
    }

    /**
     * Same, and when {@code flag} is set, stores the result in that window property inside the same
     * script, so a later evaluateJavascript reads it in order (a callback can run after the next script).
     */
    private void sendKey(String type, String key, String code, int keyCode, boolean repeat, String flag, ValueCallback<String> done) {
        String js = "(function(){var e=new KeyboardEvent('" + type + "',{key:'" + key + "',code:'" + code + "',repeat:" + repeat
                + ",bubbles:true,cancelable:true});"
                + "try{Object.defineProperty(e,'keyCode',{get:function(){return " + keyCode + "}});"
                + "Object.defineProperty(e,'which',{get:function(){return " + keyCode + "}});}catch(x){}"
                + "var t=document.activeElement||document.body||document.documentElement;"
                + "var h=!t.dispatchEvent(e);"
                + (flag != null ? "window." + flag + "=h;" : "")
                + "return h;})()";
        web.evaluateJavascript(js, done);
    }

    @Override
    public boolean dispatchKeyEvent(KeyEvent e) {
        int code = e.getKeyCode();
        int action = e.getAction();
        boolean down = action == KeyEvent.ACTION_DOWN;
        boolean up = action == KeyEvent.ACTION_UP;

        if (code == KeyEvent.KEYCODE_BACK || code == KeyEvent.KEYCODE_ESCAPE) {
            if (customView != null) {
                if (up) chrome.onHideCustomView(); // (getWebChromeClient() needs API 26)
                return true;
            }
            if (down && e.getRepeatCount() == 0) {
                backDownAt = SystemClock.uptimeMillis();
                if (!showingError) {
                    // The keydown script itself records whether the page used Back. Setting it from the
                    // callback raced the keyup check below on a busy page, and Back then quit the app
                    // although the page had called preventDefault() (found by firelab explore).
                    sendKey("keydown", "Escape", "Escape", 27, false, "__firelabBack", null);
                }
            } else if (up) {
                if (showingError || SystemClock.uptimeMillis() - backDownAt >= HOLD_TO_QUIT_MS) {
                    finish();
                    return true;
                }
                sendKey("keyup", "Escape", "Escape", 27, false, null);
                // Runs after the keydown above (evaluateJavascript keeps order).
                web.evaluateJavascript("window.__firelabBack===true", new ValueCallback<String>() {
                    @Override
                    public void onReceiveValue(String handled) {
                        if ("true".equals(handled)) return; // the page used Back itself
                        if (web.canGoBack()) web.goBack();
                        else finish();
                    }
                });
            }
            return true;
        }

        if (showingError) {
            if (up && !searching && (code == KeyEvent.KEYCODE_DPAD_CENTER || code == KeyEvent.KEYCODE_ENTER)) {
                searchedSinceOk = false;
                load();
            }
            return true;
        }

        Object[] k = keyFor(code);
        if (k == null || customView != null) return super.dispatchKeyEvent(e);
        if (down) sendKey("keydown", (String) k[0], (String) k[1], (Integer) k[2], e.getRepeatCount() > 0, null);
        else if (up) sendKey("keyup", (String) k[0], (String) k[1], (Integer) k[2], false, null);
        return true;
    }

    // ---------- lifecycle ----------

    private void hideSystemUi() {
        root.setSystemUiVisibility(View.SYSTEM_UI_FLAG_FULLSCREEN | View.SYSTEM_UI_FLAG_HIDE_NAVIGATION
                | View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY | View.SYSTEM_UI_FLAG_LAYOUT_STABLE
                | View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN | View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION);
    }

    @Override
    public void onWindowFocusChanged(boolean hasFocus) {
        super.onWindowFocusChanged(hasFocus);
        if (hasFocus) hideSystemUi();
    }

    @Override
    protected void onPause() {
        super.onPause();
        if (web != null) {
            web.onPause();
            web.pauseTimers();
        }
    }

    @Override
    protected void onResume() {
        super.onResume();
        if (web != null) {
            web.onResume();
            web.resumeTimers();
        }
    }

    @Override
    protected void onDestroy() {
        if (web != null) {
            root.removeView(web);
            web.destroy();
            web = null;
        }
        super.onDestroy();
    }
}
